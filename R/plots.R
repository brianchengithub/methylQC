## Reported against predicted age, with a transparent +/- 3 SD band around the
## fitted line.
.p_age <- function(qc, th, nsd = 3) {
  ## Select the predicted-age column by type, not by prefix. flagsamples()
  ## creates `age_outlier`, a logical, and adds it BEFORE predictages() assigns
  ## `age_horvath353`, so a bare grep("^age_") picked the flag first and the
  ## panel plotted TRUE/FALSE on the y axis instead of an age.
  agecol <- grep("^age_", names(qc), value = TRUE)
  agecol <- setdiff(agecol, grep("nprobes|nmodel|outlier", agecol, value = TRUE))
  agecol <- agecol[vapply(agecol, function(k) is.numeric(qc[[k]]), logical(1))]
  if (!length(agecol) || !"reported_age" %in% names(qc) ||
      all(is.na(qc$reported_age))) return(invisible(NULL))
  ac <- agecol[1]
  d <- qc[is.finite(qc$reported_age) & is.finite(qc[[ac]]), , drop = FALSE]
  if (nrow(d) < 3L) return(invisible(NULL))
  d$pred <- d[[ac]]

  r <- suppressWarnings(stats::cor(d$reported_age, d$pred, use = "complete.obs"))
  fit <- stats::lm(pred ~ reported_age, data = d)
  s <- stats::sd(stats::residuals(fit))
  gx <- seq(min(d$reported_age), max(d$reported_age), length.out = 100)
  band <- data.frame(reported_age = gx,
                     fit = stats::predict(fit, data.frame(reported_age = gx)))
  band$lo <- band$fit - nsd * s
  band$hi <- band$fit + nsd * s
  outside <- sum(abs(stats::residuals(fit)) > nsd * s)

  print(ggplot2::ggplot(d, ggplot2::aes(.data$reported_age, .data$pred)) +
    ggplot2::geom_ribbon(data = band,
                         ggplot2::aes(x = .data$reported_age, ymin = .data$lo,
                                      ymax = .data$hi),
                         inherit.aes = FALSE, fill = "steelblue", alpha = 0.15) +
    ggplot2::geom_line(data = band,
                       ggplot2::aes(.data$reported_age, .data$fit),
                       inherit.aes = FALSE, colour = "steelblue") +
    ggplot2::geom_abline(slope = 1, intercept = 0, colour = "grey75",
                         linetype = "dotted") +
    ggplot2::geom_point(ggplot2::aes(colour = .data$flagcat), size = 1.8) +
    .scale_flag() + th +
    ggplot2::labs(
      title = "Reported age versus epigenetic age",
      subtitle = sprintf(
        "n = %d, Pearson r = %.3f. Band is +/- %g SD of the residuals about the fitted line (%d sample(s) outside); dotted line is y = x. No mask is applied before prediction.",
        nrow(d), r, nsd, outside),
      x = "reported age (years)", y = ac))
}

