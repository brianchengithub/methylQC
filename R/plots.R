.theme_qc <- function() {
  ggplot2::theme_minimal(base_size = 10) +
    ggplot2::theme(
      panel.grid.minor = ggplot2::element_blank(),
      plot.title = ggplot2::element_text(face = "bold", size = 11),
      plot.subtitle = ggplot2::element_text(size = 9, colour = "grey30"))
}

#' Render the QC report
#'
#' @param qc per-sample metrics, already flagged.
#' @param cc the QC cache.
#' @param probe_fail named numeric vector of per-probe failure rates.
#' @param out destination PDF path.
#' @param failcsv destination for the failing-probe list.
#' @param pccsv destination for PC scores.
#' @param cfg options list.
#' @param logger optional logger.
#' @return \code{out}, invisibly.
#' @export
#' @examples
#' \dontrun{
#' qcreport(qc, cc, probe_fail, "qc_plots.pdf", "failed_probes.csv", "pc.csv")
#' }
qcreport <- function(qc, cc, probe_fail, out, failcsv, pccsv,
                     cfg = NULL, logger = NULL) {
  logger <- logger %||% nulllog()
  cfg <- cfg %||% mqcopts()
  th <- .theme_qc()
  qc$flagcat <- .flagcat(qc)

  dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)
  grDevices::pdf(out, width = 9, height = 6.5, onefile = TRUE)
  on.exit(grDevices::dev.off(), add = TRUE)

  .p_callrate(qc, cfg, th)
  .p_intensity(qc, cfg, th)
  .p_probefail(qc, cfg, th)
  .p_density(cc, qc, th)
  .p_sex(qc, cc, th)
  .p_age(qc, th)
  .p_mds(cc, qc, cfg, th)
  .p_pca(cc, qc, th, pccsv, logger)
  .p_pcvars(cc, qc, th, logger)

  ## The per-probe list is still written from the per-probe rates, even though
  ## the panel is now per-sample: it is the only place probe-level failure is
  ## reported, and downstream exclusion work needs it.
  .write_failed_probes(probe_fail, cc, cfg, failcsv, logger)

  logger$log("plots", sprintf("QC report written to %s", out))
  invisible(out)
}

.p_callrate <- function(qc, cfg, th) {
  d <- qc[order(qc$call_rate), , drop = FALSE]
  d$rank <- seq_len(nrow(d))
  print(ggplot2::ggplot(d, ggplot2::aes(.data$rank, .data$call_rate)) +
    ggplot2::geom_point(ggplot2::aes(colour = .data$flagcat), size = 1.5) +
    .scale_flag() +
    ggplot2::geom_hline(yintercept = cfg$samplemin, linetype = "dashed",
                        colour = "firebrick") + th +
    ggplot2::labs(
      title = "Sample call rate",
      subtitle = sprintf(
        "%d samples; %d below %.3f. Denominator is every probe on the array, so probes with a missing p-value count as failures. Detection threshold %.4g.",
        nrow(d), sum(isTRUE_vec(d$low_callrate)), cfg$samplemin, cfg$detp),
      x = "sample (ranked by call rate)", y = "call rate"))
}

## Ranked per-sample scatter rather than a histogram, so that the samples
## flagged on the call-rate panel can be identified here too.
.p_intensity <- function(qc, cfg, th) {
  d <- qc[order(qc$mean_intensity_raw), , drop = FALSE]
  d$rank <- seq_len(nrow(d))
  cut <- unique(stats::na.omit(qc$intensity_cutoff))[1]
  p <- ggplot2::ggplot(d, ggplot2::aes(.data$rank, .data$mean_intensity_raw)) +
    ggplot2::geom_point(ggplot2::aes(colour = .data$flagcat), size = 1.5) +
    .scale_flag() + th +
    ggplot2::labs(
      title = "Mean intensity (measured before dye bias and noob)",
      subtitle = sprintf(
        "Outliers flagged at %g MAD below the cohort median of log2 intensity; %d flagged. Absolute floor %s is a cohort-level warning only. Colour also carries the call-rate flag.",
        cfg$intmad, sum(isTRUE_vec(d$low_intensity)),
        if (is.na(cfg$intfloor)) "disabled" else sprintf("%.0f", cfg$intfloor)),
      x = "sample (ranked by mean intensity)", y = "mean intensity")
  if (length(cut) && is.finite(cut))
    p <- p + ggplot2::geom_hline(yintercept = cut, linetype = "dashed",
                                 colour = "firebrick")
  print(p)
}

## Per-sample probe failure: the fraction of the array that failed detection in
## each sample, ranked, against a horizontal cut-off.
.p_probefail <- function(qc, cfg, th) {
  d <- qc
  d$pct_failed <- 100 * (1 - d$call_rate)
  d <- d[order(d$pct_failed), , drop = FALSE]
  d$rank <- seq_len(nrow(d))
  lim <- 100 * cfg$failmin
  over <- sum(d$pct_failed >= lim, na.rm = TRUE)
  print(ggplot2::ggplot(d, ggplot2::aes(.data$rank, .data$pct_failed)) +
    ggplot2::geom_point(ggplot2::aes(colour = .data$flagcat), size = 1.5) +
    .scale_flag() +
    ggplot2::geom_hline(yintercept = lim, linetype = "dashed",
                        colour = "firebrick") + th +
    ggplot2::labs(
      title = "Probe failure rate across samples",
      subtitle = sprintf(
        "Percentage of all probes on the array failing detection at p > %.4g, per sample; %d sample(s) at or above %.0f%%. Probe-level failure rates are written to failed_probes.csv.",
        cfg$detp, over, lim),
      x = "sample (ranked by % probes failed)", y = "% of probes failed"))
}

.write_failed_probes <- function(pf, cc, cfg, failcsv, logger) {
  if (is.null(pf) || !length(pf)) return(invisible(NULL))
  keep <- rep(TRUE, length(pf))
  if (!isTRUE(cfg$inclqual) && !is.null(cc$design)) {
    dm <- align_to(cc$design, names(pf), "design mask", fill = FALSE)
    dm[is.na(dm)] <- FALSE
    keep <- !dm
  }
  v <- pf[keep]
  ids <- names(v)[v >= cfg$failmin]
  write_csv_atomic(
    data.frame(probe_id = ids, fail_rate = unname(v[ids]),
               stringsAsFactors = FALSE), failcsv)
  logger$log("plots", sprintf("%s probe(s) at or above failmin %.3f written to %s",
                              format(length(ids), big.mark = ","),
                              cfg$failmin, failcsv))
}

.p_density <- function(cc, qc, th) {
  d <- cc$density
  if (is.null(d)) return(invisible(NULL))
  n <- ncol(d$y)
  cat_by_id <- stats::setNames(as.character(qc$flagcat), qc$sample_id)
  df <- data.frame(
    x = rep(d$x, n),
    y = as.vector(d$y),
    s = rep(colnames(d$y), each = length(d$x)),
    stringsAsFactors = FALSE)
  df$flagcat <- factor(unname(cat_by_id[df$s]), levels = names(.MQC_FLAG_COLS))
  df$flagcat[is.na(df$flagcat)] <- "pass"
  df <- df[is.finite(df$y), , drop = FALSE]
  ## Flagged curves drawn last and opaque so they are visible over the cohort.
  df$flagged <- df$flagcat != "pass"
  df <- df[order(df$flagged), , drop = FALSE]
  nflag <- length(unique(df$s[df$flagged]))
  print(ggplot2::ggplot(df, ggplot2::aes(.data$x, .data$y, group = .data$s,
                                         colour = .data$flagcat)) +
    ggplot2::geom_line(ggplot2::aes(alpha = .data$flagged), linewidth = 0.4) +
    .scale_flag() +
    ggplot2::scale_alpha_manual(values = c(`FALSE` = min(1, 15 / max(1, n)),
                                           `TRUE` = 1), guide = "none") + th +
    ggplot2::labs(
      title = "Beta value density by sample",
      subtitle = sprintf("%d samples, %d flagged. Healthy arrays are bimodal with peaks near 0 and 1; a collapsed middle peak suggests a failed array.",
                         n, nflag),
      x = "beta", y = "density"))
}

## chrX against chrY, coloured by REPORTED sex, with the strict cut-off drawn
## and the call-rate/intensity failures ringed.
.p_sex <- function(qc, cc, th) {
  has_int <- all(c("sex_chrX_intensity", "sex_chrY_intensity") %in% names(qc)) &&
    any(is.finite(qc$sex_chrX_intensity) & is.finite(qc$sex_chrY_intensity))
  if (!has_int) return(invisible(NULL))

  d <- qc[is.finite(qc$sex_chrX_intensity) & is.finite(qc$sex_chrY_intensity), ,
          drop = FALSE]
  if (!nrow(d)) return(invisible(NULL))
  d$reported <- factor(ifelse(is.na(d$reported_sex), "not reported", d$reported_sex),
                       levels = c("F", "M", "not reported"))
  d$qcfail <- d$flagcat != "pass"
  cut <- attr(cc, "sex_threshold") %||% cc$sex_threshold
  called <- any(!is.na(d$inferred_sex))

  p <- ggplot2::ggplot(d, ggplot2::aes(.data$sex_chrX_intensity,
                                       .data$sex_chrY_intensity))
  ## Ring the QC failures first, so the ring sits under the point.
  if (any(d$qcfail))
    p <- p + ggplot2::geom_point(
      data = d[d$qcfail, , drop = FALSE], shape = 21, size = 4.2,
      colour = "grey20", fill = NA, stroke = 0.7)
  p <- p +
    ggplot2::geom_point(ggplot2::aes(colour = .data$reported), size = 2.2) +
    ggplot2::scale_colour_manual(
      values = c(F = "#C0392B", M = "#2E70B8", `not reported` = "grey60"),
      name = "reported sex", drop = FALSE)
  if (!is.null(cut) && is.finite(cut))
    p <- p + ggplot2::geom_hline(yintercept = cut, linetype = "dashed",
                                 colour = "grey25")

  sub <- if (called)
    sprintf(paste("Strict cut-off %s: the natural break locates the two clusters,",
                  "then the cut-off is set %g MADs above the median of the LOW",
                  "chrY cluster, whose spread is pure background. Ringed points",
                  "failed call rate or intensity."),
            if (is.null(cut) || !is.finite(cut)) "" else sprintf("at %.0f", cut),
            mqcopts()$sexcutsd)
  else
    paste("No sex was called: chrY intensity is not bimodal in this cohort",
          "(single-sex, too small, or too noisy). Ringed points failed call",
          "rate or intensity.")

  print(p + th + ggplot2::labs(
    title = "Sex chromosome intensity",
    subtitle = sub,
    x = "median chrX (X-linked) intensity",
    y = "median chrY intensity"))
}

## Reported against predicted age, with a transparent +/- 3 SD band around the
## fitted line.
.p_age <- function(qc, th, nsd = 3) {
  ## Select the predicted-age column by type, not by prefix. flagsamples()
  ## creates `age_outlier`, a logical, and adds it BEFORE predictages() assigns
  ## `age_horvath353`, so a bare grep("^age_") picked the flag first and the
  ## panel plotted TRUE/FALSE on the y axis instead of an age.
  agecol <- grep("^age_", names(qc), value = TRUE)
  agecol <- setdiff(agecol, grep("nprobes|nmodel|outlier", agecol, value = TRUE))
  agecol <- agecol[vapply(agecol, function(k) is.numeric(qc[[k]]), logical(1))]
  if (!length(agecol) || !"reported_age" %in% names(qc) ||
      all(is.na(qc$reported_age))) return(invisible(NULL))
  ac <- agecol[1]
  d <- qc[is.finite(qc$reported_age) & is.finite(qc[[ac]]), , drop = FALSE]
  if (nrow(d) < 3L) return(invisible(NULL))
  d$pred <- d[[ac]]

  r <- suppressWarnings(stats::cor(d$reported_age, d$pred, use = "complete.obs"))
  fit <- stats::lm(pred ~ reported_age, data = d)
  s <- stats::sd(stats::residuals(fit))
  gx <- seq(min(d$reported_age), max(d$reported_age), length.out = 100)
  band <- data.frame(reported_age = gx,
                     fit = stats::predict(fit, data.frame(reported_age = gx)))
  band$lo <- band$fit - nsd * s
  band$hi <- band$fit + nsd * s
  outside <- sum(abs(stats::residuals(fit)) > nsd * s)

  print(ggplot2::ggplot(d, ggplot2::aes(.data$reported_age, .data$pred)) +
    ggplot2::geom_ribbon(data = band,
                         ggplot2::aes(x = .data$reported_age, ymin = .data$lo,
                                      ymax = .data$hi),
                         inherit.aes = FALSE, fill = "steelblue", alpha = 0.15) +
    ggplot2::geom_line(data = band,
                       ggplot2::aes(.data$reported_age, .data$fit),
                       inherit.aes = FALSE, colour = "steelblue") +
    ggplot2::geom_abline(slope = 1, intercept = 0, colour = "grey75",
                         linetype = "dotted") +
    ggplot2::geom_point(ggplot2::aes(colour = .data$flagcat), size = 1.8) +
    .scale_flag() + th +
    ggplot2::labs(
      title = "Reported age versus epigenetic age",
      subtitle = sprintf(
        "n = %d, Pearson r = %.3f. Band is +/- %g SD of the residuals about the fitted line (%d sample(s) outside); dotted line is y = x. No mask is applied before prediction.",
        nrow(d), r, nsd, outside),
      x = "reported age (years)", y = ac))
}

