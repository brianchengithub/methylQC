## ---------------------------------------------------------------------------
## plots.R -- the QC report.
##
## Goal:    one multi-page PDF that shows, per sample, what is wrong and why.
## Approach: every per-sample panel carries the SAME flag colouring, so a
##          sample flagged on the call-rate panel is identifiable on the
##          intensity, density, sex, age, MDS and PCA panels too. Panels split
##          by whether a user-tunable threshold reaches them.
## Inputs:  the flagged metrics frame and the QC cache.
## Outputs: qc_plots.pdf, failed_probes.csv, pc_scores.csv.
## Usage:   qcreport(flags, cc, probe_fail, out, failcsv, pccsv)
##
## FROZEN VERSUS REGENERATED
## -------------------------
##   Regenerated by qcplots():  call rate, intensity, probe failure, density,
##                              sex, age, MDS, and the PC/metadata panels
##   Frozen after Stage 2:      the PCA and MDS coordinates themselves
##
## Everything except the coordinates is recomputed from qccache.rds, so a
## threshold change re-renders the whole report in about a second and never
## opens a matrix file. The coordinates are frozen legitimately rather than
## merely reused: pcainput() defines its probe set without reference to any
## user-tunable threshold, so re-running with a different `detp` could not
## change them.
## ---------------------------------------------------------------------------

## Fixed parameters of the PCA input. Deliberately NOT user options.
.MQC_PCA_NTOP   <- 100000L   # top-variance probes retained
.MQC_PCA_DETP   <- 0.05      # internal detection threshold, not cfg$detp
.MQC_PCA_TOLER  <- 0.01      # allow failure in up to 1% of samples

## Probes carried into the MDS distance, from the PCA input.
.MQC_MDS_NTOP   <- 5000L

## The PC/metadata pages. Six panels to a page, one page per variable. The
## standard variables always get a page; anything else in the sheet needs to
## reach MINETA against some PC, and MAXEXTRA caps how many such pages a wide
## sample sheet can add.
.MQC_PC_MINETA   <- 0.10
.MQC_PC_MAXEXTRA <- 6L

## Columns methylQC itself produces. Excluded from the PC/metadata panel so a
## component cannot be "explained" by a flag derived from the same matrix.
.MQC_DERIVED_COLS <- c(
  "sample_id", "Basename", "sentrix", "flagcat", "flag_reason", "flagged",
  "low_callrate", "low_intensity", "sex_mismatch", "sex_unknown",
  "sex_unclear", "mds_outlier", "age_outlier", "inferred_sex",
  "call_rate", "detp_threshold", "intensity_cutoff", "reported_age",
  "sex_confidence", "sex_chrX_intensity", "sex_chrY_intensity",
  "mean_intensity_raw", "mean_intensity_mu", "detected_platform")

## Chip position, parsed by discover() from the Sentrix barcode. Kept as
## candidates for the PC panels: slide, row and column are the physical
## variables most likely to carry a batch effect.
.MQC_POSITION_COLS <- c("sentrix_slide", "sentrix_row", "sentrix_col")

## One palette, used by every per-sample panel. The levels are fixed a priori
## and every scale is drawn with drop = FALSE, so all four appear in the legend
## of every panel whether or not the cohort contains any -- an absent category
## and an unflagged cohort would otherwise look identical.
.MQC_FLAG_COLS <- c(
  "OK"            = "steelblue",
  "Low detection" = "red3",
  "Low intensity" = "goldenrod3",
  "MDS outlier"   = "purple3")

#' Categorise each sample for colouring
#'
#' One sample can trip several flags, so the categories are ordered by
#' precedence: MDS outlier beats low intensity, which beats low detection. The
#' factor always carries all four levels.
#'
#' @param qc flagged metrics frame.
#' @return a factor with the levels of \code{.MQC_FLAG_COLS}.
#' @keywords internal
#' @noRd
.flagcat <- function(qc) {
  v <- ifelse(isTRUE_vec(qc$mds_outlier), "MDS outlier",
       ifelse(isTRUE_vec(qc$low_intensity), "Low intensity",
       ifelse(isTRUE_vec(qc$low_callrate), "Low detection", "OK")))
  factor(v, levels = names(.MQC_FLAG_COLS))
}

## NA-safe logical coercion; a flag that could not be computed is not a flag.
#' @keywords internal
#' @noRd
isTRUE_vec <- function(x) {
  if (is.null(x)) return(logical(0))
  x <- as.logical(x)
  x[is.na(x)] <- FALSE
  x
}

## limits= as well as drop=FALSE. drop=FALSE alone is enough in ggplot2 4.x,
## but naming the limits makes the guarantee explicit and independent of how a
## future ggplot2 treats unused factor levels.
.scale_flag <- function(name = NULL)
  ggplot2::scale_colour_manual(values = .MQC_FLAG_COLS, name = name,
                               drop = FALSE, limits = names(.MQC_FLAG_COLS),
                               na.value = "grey80")

.scale_flag_fill <- function(name = NULL)
  ggplot2::scale_fill_manual(values = .MQC_FLAG_COLS, name = name,
                             drop = FALSE, limits = names(.MQC_FLAG_COLS),
                             na.value = "grey80")

#' Build the PCA input matrix
#'
#' Selection criteria are fixed and independent of the user's options, so that
#' the PCA is stable across re-runs and comparable across cohorts of different
#' size.
#'
#' @param betas unmasked beta matrix.
#' @param detp detection p-value matrix.
#' @param design named logical design mask.
#' @param sex_probes probe IDs on the sex chromosomes.
#' @param logger optional logger.
#' @return a numeric matrix of probes by samples, free of \code{NA}.
#' @export
#' @examples
#' \dontrun{
#' bt <- pcainput(betas, detp, design, sexprobes("EPIC"))
#' }
pcainput <- function(betas, detp = NULL, design = NULL, sex_probes = character(0),
                     logger = NULL) {
  logger <- logger %||% nulllog()

  keep <- grepl("^(cg|ch)", rownames(betas))
  if (length(sex_probes)) keep <- keep & !(rownames(betas) %in% sex_probes)
  if (!is.null(design)) {
    dm <- align_to(design, rownames(betas), "design mask", fill = TRUE)
    keep <- keep & !dm
  }
  b <- betas[keep, , drop = FALSE]
  if (!nrow(b)) return(b)

  if (!is.null(detp)) {
    d <- conform_to(detp, betas, "detP matrix")[keep, , drop = FALSE]

    ## Samples that failed outright are excluded from the denominator. One
    ## dead array makes every probe's failure rate at least 1/n, which at the
    ## fixed 1% tolerance discarded the ENTIRE probe set and silently dropped
    ## the PCA, MDS and scree panels from the report.
    dead <- colMeans(is.na(d) | d > .MQC_PCA_DETP) > 0.5
    if (any(dead) && sum(!dead) >= 3L) {
      logger$log("pca", sprintf(
        "%d sample(s) failed detection almost everywhere and are excluded from the probe-selection denominator",
        sum(dead)))
      d <- d[, !dead, drop = FALSE]
    }

    fail <- rowMeans(is.na(d) | d > .MQC_PCA_DETP)
    b <- b[fail <= .MQC_PCA_TOLER, , drop = FALSE]
  }
  if (!nrow(b)) return(b)

  ## Fill the residual handful of NAs with the probe mean. At <= 1% missing
  ## this is negligible, and it removes the complete.cases fragility.
  na_idx <- which(is.na(b), arr.ind = TRUE)
  if (nrow(na_idx)) {
    rm_ <- rowMeans(b, na.rm = TRUE)
    b[na_idx] <- rm_[na_idx[, 1]]
    b <- b[is.finite(rowMeans(b)), , drop = FALSE]
  }

  v <- .rowVars(b)
  top <- order(v, decreasing = TRUE)[seq_len(min(.MQC_PCA_NTOP, length(v)))]
  out <- b[sort(top), , drop = FALSE]
  logger$log("pca", sprintf(
    "PCA input: %s probes (cg/ch, sex and design excluded, detection failure <= %.0f%%)",
    format(nrow(out), big.mark = ","), 100 * .MQC_PCA_TOLER))
  out
}

## The sentence that describes what pcainput() kept, reused by both the MDS and
## the PCA panels so the reader never has to guess what "retained" means.
.retained_text <- function(n_probes = NA) {
  sprintf(paste("Retained probes = cg/ch probes only, excluding sex chromosomes",
                "and design-masked probes, and requiring detection failure in",
                "at most %.0f%% of samples at a fixed internal p of %.2f;",
                "residual gaps filled with the probe mean, then the %s most",
                "variable kept%s."),
          100 * .MQC_PCA_TOLER, .MQC_PCA_DETP,
          format(.MQC_PCA_NTOP, big.mark = ","),
          if (is.na(n_probes)) "" else
            sprintf(" (%s entered)", format(n_probes, big.mark = ",")))
}

#' Compute the frozen PCA
#'
#' @param bt output of \code{\link{pcainput}}.
#' @param logger optional logger.
#' @return a list with \code{scores}, \code{sdev} and \code{n_probes}, or
#'   \code{NULL} when there is too little data.
#' @export
#' @examples
#' \dontrun{
#' pc <- runpca(pcainput(betas, detp, design))
#' }
runpca <- function(bt, logger = NULL) {
  logger <- logger %||% nulllog()
  if (is.null(bt) || nrow(bt) < 100L || ncol(bt) < 3L) {
    logger$log("pca", "too few probes or samples for PCA")
    return(NULL)
  }
  t0 <- Sys.time()
  ## Centred but NOT scaled. Betas already share one bounded scale, so dividing
  ## each probe by its own SD gives every probe equal weight and exactly undoes
  ## the top-variance selection pcainput() just performed; it also divides
  ## near-constant probes by floating-point residue.
  p <- stats::prcomp(t(bt), center = TRUE, scale. = FALSE)
  logger$log("pca", sprintf("PCA on %s probes x %d samples in %s",
                            format(nrow(bt), big.mark = ","), ncol(bt),
                            fmtdur(as.numeric(difftime(Sys.time(), t0, units = "secs")))))
  ## `rotation` is n_probes x n_PCs and is never used by the plots; dropping
  ## it turns a 1.2 GiB object into a few megabytes.
  list(scores = p$x, sdev = p$sdev, n_probes = nrow(bt))
}

#' Multidimensional scaling coordinates
#'
#' @param bt PCA input matrix.
#' @param logger optional logger.
#' @return a two-column matrix, or \code{NULL}.
#' @keywords internal
#' @noRd
runmds <- function(bt, logger = NULL) {
  logger <- logger %||% nulllog()
  if (is.null(bt) || ncol(bt) < 3L || !nrow(bt)) return(NULL)
  ## pcainput() returns its probes in row order, not variance order, so taking
  ## the first rows sampled one end of the manifest rather than the most
  ## informative probes. Take the most variable instead.
  n <- min(.MQC_MDS_NTOP, nrow(bt))
  sub <- if (n < nrow(bt)) {
    v <- .rowVars(bt)
    bt[sort(order(v, decreasing = TRUE)[seq_len(n)]), , drop = FALSE]
  } else bt
  d <- tryCatch(stats::dist(t(sub)), error = function(e) NULL)
  if (is.null(d)) return(NULL)
  m <- tryCatch(stats::cmdscale(d, k = 2), error = function(e) NULL)
  if (is.null(m) || !is.matrix(m) || ncol(m) < 2L) return(NULL)
  colnames(m) <- c("MDS1", "MDS2")
  attr(m, "n_probes") <- n
  m
}

#' Flag samples far from the cohort centroid in MDS space
#'
#' Distance is measured from the coordinate-wise median, which is unaffected by
#' the outliers it is meant to find, and scaled by the median absolute
#' deviation of those distances.
#'
#' @param mds a two-column MDS coordinate matrix.
#' @param nsd distance, in SDs, beyond which a sample is an outlier.
#' @return a named logical vector, with the radius as an attribute.
#' @export
#' @examples
#' m <- cbind(MDS1 = c(0, 0.1, -0.1, 5), MDS2 = c(0, -0.1, 0.1, 5))
#' rownames(m) <- paste0("s", 1:4)
#' mdsoutlier(m)
mdsoutlier <- function(mds, nsd = NULL) {
  nsd <- .opt(nsd, "mdssd")
  if (is.null(mds) || !is.matrix(mds) || nrow(mds) < 4L) return(NULL)
  centre <- apply(mds, 2L, stats::median, na.rm = TRUE)
  d <- sqrt(rowSums(sweep(mds, 2L, centre)^2))
  s <- stats::mad(d)
  if (!is.finite(s) || s <= 0) s <- stats::sd(d)
  if (!is.finite(s) || s <= 0) return(NULL)
  r <- stats::median(d) + nsd * s
  out <- stats::setNames(d > r, rownames(mds))
  attr(out, "radius") <- r
  attr(out, "centre") <- centre
  attr(out, "dist") <- d
  out
}

#' Per-sample beta density curves
#'
#' Cached rather than recomputed, because the density of a beta matrix does
#' not depend on any threshold.
#'
#' @param betas beta matrix.
#' @param nsub probes sampled per column.
#' @return a list with \code{x} and \code{y}.
#' @keywords internal
#' @noRd
betadensity <- function(betas, nsub = 20000L) {
  if (is.null(betas) || !ncol(betas)) return(NULL)
  ## Reproducible without stealing the caller's random stream: save and restore
  ## .Random.seed around the draw.
  old <- if (exists(".Random.seed", envir = globalenv(), inherits = FALSE))
    get(".Random.seed", envir = globalenv()) else NULL
  on.exit({
    if (is.null(old)) suppressWarnings(rm(".Random.seed", envir = globalenv()))
    else assign(".Random.seed", old, envir = globalenv())
  }, add = TRUE)
  set.seed(1L)
  idx <- if (nrow(betas) > nsub) sample.int(nrow(betas), nsub) else seq_len(nrow(betas))
  gx <- seq(0, 1, length.out = 512L)
  ys <- vapply(seq_len(ncol(betas)), function(j) {
    v <- betas[idx, j]; v <- v[is.finite(v)]
    if (length(v) < 100L) return(rep(NA_real_, length(gx)))
    stats::density(v, from = 0, to = 1, n = length(gx))$y
  }, numeric(length(gx)))
  colnames(ys) <- colnames(betas)
  list(x = gx, y = ys)
}


