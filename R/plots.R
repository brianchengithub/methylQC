  p <- ggplot2::ggplot(d, ggplot2::aes(.data$MDS1, .data$MDS2))
  if (!is.null(ring))
    p <- p + ggplot2::geom_path(data = ring,
                                ggplot2::aes(.data$x, .data$y),
                                inherit.aes = FALSE, colour = "firebrick",
                                linetype = "dashed", linewidth = 0.4)
  print(p +
    ggplot2::geom_point(ggplot2::aes(colour = .data$flagcat), size = 1.8) +
    .scale_flag() + th +
    ggplot2::labs(
      title = "MDS of retained probes",
      subtitle = paste0(
        .retained_text(attr(m, "n_probes")), " ",
        if (is.null(o)) "" else sprintf(
          "Dashed circle is %g SD from the cohort centroid; %d sample(s) outside it.",
          cfg$mdssd, sum(o)))))
}

